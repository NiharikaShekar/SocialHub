class SocialGNN(torch.nn.Module):
    def __init__(self, hidden_channels, out_channels):
        super().__init__()
        # SAGEConv aggregates neighbors
        self.conv1 = SAGEConv((-1, -1), hidden_channels)
        self.conv2 = SAGEConv((-1, -1), out_channels)

    def forward(self, x, edge_index):
        x = self.conv1(x, edge_index)
        x = F.relu(x)
        x = self.conv2(x, edge_index)
        return x

# Input dimension is -1 (lazy load), Hidden 64, Output 32
model = SocialGNN(hidden_channels=64, out_channels=32)

# Convert generic GNN to Heterogeneous GNN
# This creates specific weights for (user-major) vs (user-hobby)
model = to_hetero(model, data.metadata(), aggr='sum').to(device)

optimizer = torch.optim.Adam(model.parameters(), lr=0.005)

