# 1. DEFINE VALID UIC TIME BLOCKS (30-min chunks)
days = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri']
all_slots = []
for d in days:
    for h in range(8, 18): # 8 AM to 6 PM
        for m in [0, 30]:
            all_slots.append(f"{d}_{h:02d}:{m:02d}")

all_slots_set = set(all_slots)

# 2. CREATE A MASTER SCHEDULE FOR EVERY COURSE IN YOUR CATALOG
# This ensures that everyone taking "CS 111" gets the SAME time slots.

mw_starts = [8, 9.5, 11, 12.5, 14, 15.5]
tth_starts = [8, 9.5, 11, 12.5, 14, 15.5]

def generate_class_time_blocks():
    """Generates 3 blocks (1.5 hours) for a Mon/Wed or Tue/Thu pattern"""
    pattern = random.choice(['MW', 'TTh'])
    start_hour = random.choice(mw_starts)

    blocks = []
    current_days = ['Mon', 'Wed'] if pattern == 'MW' else ['Tue', 'Thu']

    for day in current_days:
        h = int(start_hour)
        m = int((start_hour % 1) * 60)

        # Add 3 blocks (0, 30, 60 mins)
        for _ in range(3):
            blocks.append(f"{day}_{h:02d}:{m:02d}")
            m += 30
            if m >= 60:
                h += 1
                m -= 60
    return blocks

# Flatten your catalog to get a list of all unique courses
all_unique_courses = set()
for major, course_list in course_catalog.items():
    for c in course_list:
        all_unique_courses.add(c)

# Create the Master Map: { "CS 111...": ['Mon_10:00', 'Mon_10:30', ...], ... }
master_course_schedule = {}
for course in all_unique_courses:
    master_course_schedule[course] = generate_class_time_blocks()

print(f"Generated schedules for {len(master_course_schedule)} unique courses.\n")

# Print the schedule for ALL courses
print("--- Master Course Schedule ---")
for course, slots in sorted(master_course_schedule.items()):
    print(f"{course}: {slots}")

def calculate_student_schedule(row):
    my_courses = row['Courses'] # List like ['CS 111...', 'MATH 180...']

    busy_slots = set()

    # Look up the "Official" time for each course
    for course_name in my_courses:
        if course_name in master_course_schedule:
            # Add the specific blocks for this course
            course_times = master_course_schedule[course_name]
            busy_slots.update(course_times)

    # Calculate Free Slots (The Inverse)
    # We want to link students based on when they are FREE
    free_slots = list(all_slots_set - busy_slots)

    return free_slots

# Apply to DataFrame
