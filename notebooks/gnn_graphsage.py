# 3. Helper Function to Print Results
def show_recommendations(user_idx):
    # 1. Get more candidates (e.g., Top 50) instead of just 5
    # We broaden the search so we have room to filter/sort
    distances, indices = knn.kneighbors([user_embeddings[user_idx]], n_neighbors=50)

    target_user = df.iloc[user_idx]
    target_age = target_user['Age']

    print(f"\n============================================================")
    print(f"👤  FOCUS USER: {target_user['Name']}")
    print(f"    Major: {target_user['Major']} | Age: {target_age}")
    print(f"    Likes: {target_user['Hobbies']}")
    print(f"============================================================")

    print("⬇️  TOP 5 RECOMMENDED FRIENDS (Age Adjusted) ⬇️")

    candidates = []

    # 2. Loop through candidates and calculate a "Hybrid Score"
    for rank, neighbor_idx in enumerate(indices[0][1:]): # Skip self
        friend = df.iloc[neighbor_idx]
        friend_age = friend['Age']

        # Raw Similarity from GNN (0.0 to 1.0)
        raw_score = (1 - distances[0][rank+1])

        # Calculate Age Penalty
        # Rule: Subtract 1.5% from score for every year of difference
        age_diff = abs(target_age - friend_age)
        age_penalty = age_diff * 0.015

        # Final Adjusted Score
        final_score = raw_score - age_penalty

        candidates.append({
            'idx': neighbor_idx,
            'name': friend['Name'],
            'age': friend_age,
            'major': friend['Major'],
            'hobbies': friend['Hobbies'],
            'bio': friend['Unique Quality'],
            'score': final_score * 100 # Convert to percentage
        })

    # 3. Sort by the NEW Final Score
    candidates.sort(key=lambda x: x['score'], reverse=True)

    # 4. Print top 5
    for i, person in enumerate(candidates[:5]):
        print(f"\n{i+1}. {person['name']} (Score: {person['score']:.1f}%)")
        print(f"   🎂 Age:   {person['age']} (Gap: {abs(target_age - person['age'])} yrs)")
