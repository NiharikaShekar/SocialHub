# ==============================================================================
print("\n[Step 4/5] Training Embeddings...")

def train():
    model.train()
    optimizer.zero_grad()

    # 1. Forward Pass: Get embeddings for all nodes
    out_dict = model(data.x_dict, data.edge_index_dict)

    # 2. Define Loss: Link Prediction on User-Hobby edges
    # We want Users to be close to Hobbies they actually like

    # Get edge indices for 'user' -> 'likes' -> 'hobby'
    # Note: After ToUndirected, PyG might rename edges. We use original names if possible
    # or access via the edge_types list.
    edge_type = ('user', 'likes', 'hobby')
    src, dst = data[edge_type].edge_index

    user_embed = out_dict['user'][src]
    hobby_embed = out_dict['hobby'][dst]

    # Positive Score (Dot product)
    pos_score = (user_embed * hobby_embed).sum(dim=1)

    # Negative Sampling (Random mismatching hobbies)
    rand_dst = torch.randint(0, data['hobby'].num_nodes, (len(src),), device=device)
    neg_hobby_embed = out_dict['hobby'][rand_dst]
    neg_score = (user_embed * neg_hobby_embed).sum(dim=1)

    # Margin Ranking Loss or BPR Loss
    # Maximize (Pos - Neg)
    loss = -torch.log(torch.sigmoid(pos_score - neg_score) + 1e-15).mean()

    loss.backward()
    optimizer.step()
    return loss.item()

