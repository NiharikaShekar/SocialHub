# ==============================================================================
# 6. TRAINING LOOP (WEIGHTED LOSS)
# ==============================================================================
print("\n[Step 4/6] Training with Weighted Objectives (Courses > Hobbies)...")

def train_step():
    model.train()
    optimizer.zero_grad()
    out = model(train_data.x_dict, train_data.edge_index_dict)

    # --- Loss 1: Hobbies (Social Factor) ---
    src_h, dst_h = train_data['user', 'likes', 'hobby'].edge_label_index
    pos_h = (out['user'][src_h] * out['hobby'][dst_h]).sum(dim=-1)
    # Negative samples
    neg_dst_h = torch.randint(0, data['hobby'].num_nodes, (len(src_h),), device=device)
    neg_h = (out['user'][src_h] * out['hobby'][neg_dst_h]).sum(dim=-1)
    loss_hobby = -torch.log(torch.sigmoid(pos_h - neg_h) + 1e-15).mean()

    # --- Loss 2: Courses (Study Factor) - WEIGHTED HIGHER ---
    src_c, dst_c = train_data['user', 'enrolled_in', 'course'].edge_label_index
    pos_c = (out['user'][src_c] * out['course'][dst_c]).sum(dim=-1)
    # Negative samples
    neg_dst_c = torch.randint(0, data['course'].num_nodes, (len(src_c),), device=device)
    neg_c = (out['user'][src_c] * out['course'][neg_dst_c]).sum(dim=-1)
    loss_course = -torch.log(torch.sigmoid(pos_c - neg_c) + 1e-15).mean()

    # --- Total Weighted Loss ---
    # 5.0 multiplier forces model to prioritize Course overlap
    total_loss = loss_hobby + (5.0 * loss_course)

    total_loss.backward()
    optimizer.step()
    return total_loss.item()

@torch.no_grad()
def test_step(data_split):
    model.eval()
    out = model(data_split.x_dict, data_split.edge_index_dict)

    # Evaluate on Course prediction accuracy (The priority)
    src, dst = data_split['user', 'enrolled_in', 'course'].edge_label_index
    pos = (out['user'][src] * out['course'][dst]).sum(dim=-1)
    neg_dst = torch.randint(0, data['course'].num_nodes, (len(src),), device=device)
    neg = (out['user'][src] * out['course'][neg_dst]).sum(dim=-1)

    y_true = torch.cat([torch.ones(pos.size(0)), torch.zeros(neg.size(0))]).cpu().numpy()
    y_score = torch.cat([pos, neg]).sigmoid().cpu().numpy()
    return roc_auc_score(y_true, y_score)

# Run Training
MAX_EPOCHS = 60
