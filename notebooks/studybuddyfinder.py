patience_counter = 0

for epoch in range(1, MAX_EPOCHS + 1):
    loss = train_step()
    val_auc = test_step(val_data)

    if val_auc > best_val_auc:
        best_val_auc = val_auc
        patience_counter = 0
        print(f"Epoch {epoch:02d} | Loss: {loss:.4f} | Course AUC: {val_auc:.4f} *")
    else:
        patience_counter += 1
        if epoch % 10 == 0:
            print(f"Epoch {epoch:02d} | Loss: {loss:.4f} | Course AUC: {val_auc:.4f}")

    if patience_counter > 15:
        print("🛑 Early stopping triggered.")
        break

