def recommend_study_buddy(user_idx):
    target_user = df.iloc[user_idx]

    # Safe Parsing
    try:
        my_courses = set(ast.literal_eval(target_user['Courses'])) if isinstance(target_user['Courses'], str) else set(target_user['Courses'])
        my_slots = set(ast.literal_eval(target_user['Free_Slots'])) if isinstance(target_user['Free_Slots'], str) else set(target_user['Free_Slots'])
    except:
        my_courses, my_slots = set(), set()

    print(f"\n📘 FOCUS STUDENT: {target_user['Name']}")
    print(f"   Major: {target_user['Major']}")
    print(f"   Courses: {list(my_courses)}")
    print("=" * 70)

    # A. Retrieve Top 50 Candidates (AI Layer)
    distances, indices = knn.kneighbors([user_embeddings[user_idx]])

    candidates = []

    # B. Rank Candidates (Logic Layer)
    for rank, neighbor_idx in enumerate(indices[0][1:]): # Skip self
        friend = df.iloc[neighbor_idx]

        try:
            friend_courses = set(ast.literal_eval(friend['Courses'])) if isinstance(friend['Courses'], str) else set(friend['Courses'])
            friend_slots = set(ast.literal_eval(friend['Free_Slots'])) if isinstance(friend['Free_Slots'], str) else set(friend['Free_Slots'])
        except:
            continue

        # Overlaps
        shared_courses = list(my_courses.intersection(friend_courses))
        shared_slots = list(my_slots.intersection(friend_slots))

        gnn_score = (1 - distances[0][rank+1]) # 0 to 1

        # --- THE STUDY BUDDY FORMULA ---
        # 1. Shared Class = +10.0 points
        # 2. Shared Time = +0.05 points (Capped at 3.0)
        # 3. AI Similarity = +2.0 points
        final_score = (len(shared_courses) * 10.0) + \
                      (min(len(shared_slots) * 0.05, 3.0)) + \
                      (gnn_score * 2.0)

        candidates.append({
            'name': friend['Name'],
            'major': friend['Major'],
            'shared_courses': shared_courses,
            'shared_slots_count': len(shared_slots),
            'example_slot': shared_slots[0] if shared_slots else None,
            'final_score': final_score,
            'gnn_match': gnn_score * 100
        })

    # C. Sort and Display
    candidates.sort(key=lambda x: x['final_score'], reverse=True)

    for i, person in enumerate(candidates[:5]):
        print(f"{i+1}. {person['name']} (Score: {person['final_score']:.2f})")
        print(f"   🎓 Major: {person['major']}")

        if person['shared_courses']:
            print(f"   ✅ SHARED CLASS: {', '.join(person['shared_courses'])}")
        else:
            print(f"   ❌ No shared classes")

        print(f"   ⏰ Free Time Match: {person['shared_slots_count']} blocks (e.g., {person['example_slot']})")
        print(f"   🧠 Profile Match: {person['gnn_match']:.1f}%")
        print("-" * 30)

