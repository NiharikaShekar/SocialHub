def train_step():
    model.train()
    optimizer.zero_grad()

    out = model(train_data.x_dict, train_data.edge_index_dict)
    edge_type = ('user', 'likes', 'hobby')
    src, dst = train_data[edge_type].edge_label_index
    pos_score = (out['user'][src] * out['hobby'][dst]).sum(dim=-1)
    neg_dst = torch.randint(0, data['hobby'].num_nodes, (len(src),), device=device)
    neg_score = (out['user'][src] * out['hobby'][neg_dst]).sum(dim=-1)
    loss = -torch.log(torch.sigmoid(pos_score - neg_score) + 1e-15).mean()

    loss.backward()
    optimizer.step()
    return loss.item()

@torch.no_grad()
def test_step(data_split):
    model.eval()
    out = model(data_split.x_dict, data_split.edge_index_dict)

    edge_type = ('user', 'likes', 'hobby')
    src, dst = data_split[edge_type].edge_label_index
    pos_score = (out['user'][src] * out['hobby'][dst]).sum(dim=-1)
    neg_dst = torch.randint(0, data['hobby'].num_nodes, (len(src),), device=device)
    neg_score = (out['user'][src] * out['hobby'][neg_dst]).sum(dim=-1)

    y_true = torch.cat([torch.ones(pos_score.size(0)), torch.zeros(neg_score.size(0))]).cpu().numpy()
    y_score = torch.cat([pos_score, neg_score]).sigmoid().cpu().numpy()
    auc = roc_auc_score(y_true, y_score)
    k = 10
    hits = 0
    total = 0
    sample_indices = torch.randperm(len(src))[:500]

    user_embeds = out['user']
    hobby_embeds = out['hobby']

    for idx in sample_indices:
        u_idx = src[idx]
        real_hobby = dst[idx]
        all_scores = torch.matmul(user_embeds[u_idx], hobby_embeds.t())
        _, top_indices = torch.topk(all_scores, k)

        if real_hobby in top_indices:
            hits += 1
        total += 1

    hit_rate = hits / total

    return auc, hit_rate

